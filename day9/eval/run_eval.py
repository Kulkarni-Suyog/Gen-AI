"""Compare Day 8 retrieval configurations A and B against the 15-question set."""
import json
from pathlib import Path
from app.vectorstore import rebuild_index, search_chunks

BASE = Path(__file__).resolve().parents[1]
QUESTIONS = BASE / "eval" / "eval_set.json"
README = BASE / "README.md"


def main():
    questions = json.loads(QUESTIONS.read_text(encoding="utf-8"))
    scores = {}
    detailed = {}
    for config, top_k in (("A", 3), ("B", 5)):
        rebuild_index(config)
        hits = 0
        details = []
        for item in questions:
            results = search_chunks(item["question"], top_k=top_k, config=config)
            found = {str(r.get("metadata", {}).get("record_id", "")) for r in results}
            expected = set(item["expected_record_ids"])
            success = bool(found & expected) if item["answerable"] else not found
            if success:
                hits += 1
            details.append({"id": item["id"], "question": item["question"], "expected": sorted(expected), "retrieved": sorted(found), "pass": success})
        scores[config] = hits
        detailed[config] = details
    winner = "A" if scores["A"] >= scores["B"] else "B"
    rows = ["# Day 8 Retrieval Evaluation", "", "Results are generated by running this script locally with the embedding model and ChromaDB installed.", "", "| Configuration | Chunking | Top-k | Hits / 15 |", "|---|---|---:|---:|"]
    rows.append(f"| A | One chunk per GST record | 3 | {scores['A']} / 15 |")
    rows.append(f"| B | 250-character chunks, 40-character overlap | 5 | {scores['B']} / 15 |")
    rows.extend(["", f"**Winner: Configuration {winner}** based on retrieval hit rate.", "", "## Question-level results", ""])
    for config in ("A", "B"):
        rows.extend([f"### Configuration {config}", "", "| ID | Question | Expected IDs | Retrieved IDs | Pass |", "|---|---|---|---|---|"])
        for d in detailed[config]:
            rows.append(f"| {d['id']} | {d['question']} | {', '.join(d['expected']) or 'none'} | {', '.join(d['retrieved']) or 'none'} | {'Yes' if d['pass'] else 'No'} |")
        rows.append("")
    README.write_text("\n".join(rows), encoding="utf-8")
    print(f"Configuration A: {scores['A']}/15")
    print(f"Configuration B: {scores['B']}/15")
    print(f"Winner: {winner}")
    print(f"Updated {README}")

if __name__ == "__main__":
    main()
